export function buildTimeline(currentStage: OrderStatus, createdAtDate: string = '17 Sep 2026'): TimelineEntry[] {
  const currentIndex = ORDER_STAGE_ORDER.indexOf(currentStage);

  return ORDER_STAGES_CONFIG.map((config, index) => {
    const isCompleted = index < currentIndex;
    const isCurrent = index === currentIndex;

    let timeStr = 'Pending';
    if (isCompleted || isCurrent) {
      const dayOffset = Math.max(0, Math.floor(index * 0.9));
      timeStr = `${17 + dayOffset} Sep 2026, ${10 + (index % 8)}:30 hrs`;
    }

    return {
      stage: config.stage,
      label: config.label,
      location: config.location,
      note: config.note,
      timestamp: timeStr,
      completed: isCompleted,
      current: isCurrent
    };
  });
}

